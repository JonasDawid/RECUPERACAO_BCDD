CREATE TABLE CLIENTES ( 
    ID_CLIENTES INT AUTO_INCREMENT,
    NOME VARCHAR (100) NOT NULL,
    EMAIL VARCHAR (120) NOT NULL,
    TELEFONE CHAR(12) UNIQUE,
    ATIVO BOOLEAN DEFAULT TRUE,

    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTES),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)

);


CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT,
    NOME VARCHAR (20) NOT NULL,
    CATEGORIA VARCHAR (200) NOT NULL,

    CONSTRAINT PK_PLATAFORMA PRIMARY KEY (ID_PLATAFORMA),
    CONSTRAINT UQ_CATEGORIA UNIQUE (CATEGORIA)
);

CREATE TABLE JOGOS (
    ID_JOGOS INT AUTO_INCREMENT,
    TITULO VARCHAR (50) NOT NULL,
    CODIGO_DE_IDENTIFICACAO CHAR (7) UNIQUE,
    LANCAMENTO DATETIME(4) NOT NULL,
    QUANTIDADE_DISPONIVEL CHAR (15) NOT NULL,
    PLATAFORMA VARCHAR (20) NOT NULL,
    CATEGORIA VARCHAR(15) NOT NULL

    CONSTRAINT FK_PLATAFORMA
    FOREIGN KEY (ID_PLATAFORMA)
    REFERENCES (ID_PLATAFORMA)

    CONSTRAINT FK_CATEGORIA 
    FOREIGN KEY (ID_CATEGORIA)
    REFERENCES ( ID_CATEGORIA)
    ); 

   CREATE TABLE LOCACAO (
    ID_LOCACACAO INT AUTO_INCREMENT,
